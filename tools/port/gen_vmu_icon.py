#!/usr/bin/env python3
"""Vivid Dolls port - convert a 32x32 PNG into the Dreamcast VMU file icon format.

    python3 -I tools/port/gen_vmu_icon.py port/assets/vmu_icon.png OUT.c

Output: a C file with
    const unsigned short vd_vmu_icon_pal[16];   ARGB4444 palette
    const unsigned char  vd_vmu_icon_data[512]; 4 bpp, 32x32, high nibble = left pixel
as KOS vmu_pkg_t.icon_pal / icon_data expect. The image is quantised to 16 colours
(k-means on the ARGB4444 colours; fully transparent pixels share one entry).
No third-party modules needed (own PNG decoder: 8-bit RGB/RGBA/grey/palette, non-interlaced).
"""
import struct
import sys
import zlib


def read_png(path):
    data = open(path, 'rb').read()
    if data[:8] != b'\x89PNG\r\n\x1a\n':
        sys.exit('%s: not a PNG' % path)
    pos, idat, plte, trns = 8, b'', None, None
    w = h = depth = ctype = interlace = None
    while pos < len(data):
        n, typ = struct.unpack('>I4s', data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        pos += 12 + n
        if typ == b'IHDR':
            w, h, depth, ctype, _, _, interlace = struct.unpack('>IIBBBBB', body)
        elif typ == b'PLTE':
            plte = body
        elif typ == b'tRNS':
            trns = body
        elif typ == b'IDAT':
            idat += body
        elif typ == b'IEND':
            break
    if depth != 8 or interlace != 0 or ctype not in (0, 2, 3, 4, 6):
        sys.exit('%s: unsupported PNG (need 8-bit, non-interlaced)' % path)
    bpp = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[ctype]
    raw = zlib.decompress(idat)
    stride = w * bpp
    rows, prev, p = [], bytearray(stride), 0
    for _ in range(h):
        f = raw[p]
        line = bytearray(raw[p + 1:p + 1 + stride])
        p += 1 + stride
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            if f == 1:
                line[i] = (line[i] + a) & 0xFF
            elif f == 2:
                line[i] = (line[i] + b) & 0xFF
            elif f == 3:
                line[i] = (line[i] + ((a + b) >> 1)) & 0xFF
            elif f == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                pr = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                line[i] = (line[i] + pr) & 0xFF
        rows.append(line)
        prev = line
    px = []
    for line in rows:
        for x in range(w):
            q = line[x * bpp:(x + 1) * bpp]
            if ctype == 6:
                px.append(tuple(q))
            elif ctype == 2:
                px.append((q[0], q[1], q[2], 255))
            elif ctype == 0:
                px.append((q[0], q[0], q[0], 255))
            elif ctype == 4:
                px.append((q[0], q[0], q[0], q[1]))
            else:
                i = q[0]
                al = trns[i] if trns and i < len(trns) else 255
                px.append((plte[i * 3], plte[i * 3 + 1], plte[i * 3 + 2], al))
    return w, h, px


def to4444(c):
    r, g, b, a = c
    return ((a >> 4) << 12) | ((r >> 4) << 8) | ((g >> 4) << 4) | (b >> 4)


def quantise(px, k=16):
    """k-means in RGBA space; transparent pixels (alpha < 128) map to one entry."""
    opaque = [c for c in px if c[3] >= 128]
    has_clear = len(opaque) != len(px)
    kk = k - 1 if has_clear else k
    uniq = sorted(set(opaque))
    if len(uniq) <= kk:
        cents = [list(c) for c in uniq]
    else:
        # deterministic start: spread over the colours sorted by luminance
        uniq.sort(key=lambda c: 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2])
        cents = [list(uniq[(i * (len(uniq) - 1)) // (kk - 1)]) for i in range(kk)]
        for _ in range(30):
            sums = [[0, 0, 0, 0, 0] for _ in cents]
            for c in opaque:
                j = min(range(len(cents)), key=lambda j: sum((c[t] - cents[j][t]) ** 2 for t in range(4)))
                s = sums[j]
                for t in range(4):
                    s[t] += c[t]
                s[4] += 1
            new = [[s[t] / s[4] for t in range(4)] if s[4] else cents[j] for j, s in enumerate(sums)]
            if new == cents:
                break
            cents = new
    pal = [tuple(int(round(v)) for v in c) for c in cents]
    if has_clear:
        pal.append((0, 0, 0, 0))
    while len(pal) < k:
        pal.append((0, 0, 0, 0))
    idx = []
    for c in px:
        if c[3] < 128 and has_clear:
            idx.append(len(cents))
        else:
            idx.append(min(range(len(cents)), key=lambda j: sum((c[t] - pal[j][t]) ** 2 for t in range(4))))
    return pal, idx


def main():
    if len(sys.argv) != 3:
        sys.exit('usage: gen_vmu_icon.py ICON.png OUT.c')
    w, h, px = read_png(sys.argv[1])
    if (w, h) != (32, 32):
        sys.exit('%s: icon must be 32x32 (is %dx%d)' % (sys.argv[1], w, h))
    pal, idx = quantise(px)
    data = bytes((idx[i] << 4) | idx[i + 1] for i in range(0, 1024, 2))
    out = ['/* Generated by tools/port/gen_vmu_icon.py from %s - do not edit. */' % sys.argv[1].split('/')[-1],
           'const unsigned short vd_vmu_icon_pal[16] = {',
           '    ' + ', '.join('0x%04X' % to4444(c) for c in pal),
           '};',
           'const unsigned char vd_vmu_icon_data[512] = {']
    for i in range(0, 512, 16):
        out.append('    ' + ', '.join('0x%02X' % b for b in data[i:i + 16]) + ',')
    out.append('};')
    open(sys.argv[2], 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
