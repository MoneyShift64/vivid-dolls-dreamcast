#!/usr/bin/env python3
"""Generate port/vd_jpeg64_tables.h from baserom.z64 (the game's own tables)."""
import struct
ROM = open('baserom.z64', 'rb').read()
V2R = lambda v: v - 0x7FFFF400          # main segment: RAM 0x80000400 = ROM 0x1000

def arr(name, ctype, vals, per=12):
    out = [f'static const {ctype} {name}[{len(vals)}] = {{']
    for i in range(0, len(vals), per):
        out.append('    ' + ', '.join(str(v) for v in vals[i:i+per]) + ',')
    return '\n'.join(out) + '\n};\n'

def s16(addr, n): return list(struct.unpack(f'>{n}h', ROM[V2R(addr):V2R(addr) + 2*n]))
def f32(addr, n): return list(struct.unpack(f'>{n}f', ROM[V2R(addr):V2R(addr) + 4*n]))

h = ['/* Generated by tools/gen_port_tables.py from baserom.z64 - do not edit. */',
     '#ifndef VD_JPEG64_TABLES_H', '#define VD_JPEG64_TABLES_H', '#include "vd_types.h"', '']
h.append(arr('vd_j64_zigzag', 'u8', [struct.unpack('>I', ROM[V2R(0x80038FD0)+4*i:V2R(0x80038FD0)+4*i+4])[0] for i in range(64)], 16))
h.append(arr('vd_j64_quant_luma', 'float', [f'{v:.1f}f' for v in f32(0x800390D0, 64)], 8))
h.append(arr('vd_j64_quant_chroma', 'float', [f'{v:.1f}f' for v in f32(0x800391D0, 64)], 8))
# Huffman decode tables: valptr / mincode / maxcode (18 entries each) + huffval
for nm, base, nvals in (('dc_luma', 0x80039B50, 12), ('dc_chroma', 0x80039BE0, 12),
                        ('ac_luma', 0x80039C70, 162), ('ac_chroma', 0x80039E20, 162)):
    h.append(arr(f'vd_j64_{nm}_valptr', 'u16', [v & 0xFFFF for v in s16(base, 18)], 9))
    h.append(arr(f'vd_j64_{nm}_mincode', 'u16', [v & 0xFFFF for v in s16(base + 0x24, 18)], 9))
    h.append(arr(f'vd_j64_{nm}_maxcode', 'u16', [v & 0xFFFF for v in s16(base + 0x48, 18)], 9))
    h.append(arr(f'vd_j64_{nm}_huffval', 'u8', [v & 0xFF for v in s16(base + 0x6C, nvals)], 18))
h.append(arr('vd_j64_to5bit', 'u8', list(ROM[V2R(0x8003A014):V2R(0x8003A014) + 256]), 32))
h.append('#endif')
open('port/vd_jpeg64_tables.h', 'w').write('\n'.join(h) + '\n')
print('wrote port/vd_jpeg64_tables.h')
